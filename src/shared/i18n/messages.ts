export function translateText(locale: Locale, value: string): string {
  if (locale === 'en') return auditLabels[value] || value;
  if (spanish[value] !== undefined) return spanish[value];
  const trimmed = value.trim();
  if (spanish[trimmed] !== undefined) return value.replace(trimmed, spanish[trimmed]);
  const patterns: [RegExp, (m: RegExpMatchArray) => string][] = [
    [/^Use at least (\d+) characters\.$/, m => `Usa al menos ${m[1]} caracteres.`],
    [/^Minimum: (.+)$/, m => `Mínimo: ${m[1]}`],
    [/^Maximum: (.+)$/, m => `Máximo: ${m[1]}`],
    [/^Enter a valid (signed )?number with at most (\d+) decimal places\.$/, m => `Ingresa un número ${m[1]?'con signo ':''}con máximo ${m[2]} decimales.`],
    [/^(.+) must contain (\d+)–(\d+) characters\.$/, m => `${translateText(locale,m[1])} debe tener entre ${m[2]} y ${m[3]} caracteres.`],
    [/^Enter a whole number between (.+) and (.+)\.$/, m => `Ingresa un número entero entre ${m[1]} y ${m[2]}.`],
    [/^Your private workspace code is (.+)\. Keep it for your next sign-in\.$/, m => `Tu código es ${m[1]}. Guárdalo para volver a ingresar.`],
    [/^Issue (REQ-.+)$/, m => `Entregar ${m[1]}`], [/^Receive (.+)$/, m => `Recibir ${m[1]}`], [/^Reorder policy · (.+)$/, m => `Reposición · ${translateText(locale, m[1])}`],
    [/^Assign equipment · (.+)$/, m => `Vincular equipo · ${m[1]}`], [/^Power profile · (.+)$/, m => `Perfil de potencia · ${m[1]}`],
    [/^Acknowledged by (.+)$/, m => `Reconocida por ${m[1]}`], [/^Seed (\d+) · (\d+) identical synthetic jobs$/, m => `Semilla ${m[1]} · ${m[2]} trabajos sintéticos equivalentes`],
  ];
  for (const [pattern, render] of patterns) { const match = value.match(pattern); if (match) return render(match); }
  return value;
}
